//! 读会话名：**从推导出的头部行里 OCR 出对方的名字**。
//!
//! ## 为什么它住在这一层（2026-10-21，票 77）
//!
//! 这段代码原先在 `ui/src-tauri/src/watch.rs` 里（产品侧），
//! 而 `xtask perceive` 那条**探针**另写了一套读名字的逻辑
//! （走整帧 OCR 的归类结果）⇒ **两条不同的路**。
//!
//! ⚠ 后果不是「重复代码难看」，是**探针证明不了产品**：
//! 探针打印「OCR 读到的会话名：小号」，而产品那条路在那时**读不到**
//! （2× 下 WinRT 读不到窄带里的小字）——**两句话同时为真**，
//! 没有任何报错。判据一句话：**探针的输出能不能证明「产品那条路」**？
//!
//! ⇒ 现在**只有这一份实现**，产品与探针都调它 ⇒ 探针那行字**才**能证明产品。
//!
//! ## 它与身份闸是**两件事**
//!
//! 闸（[`crate::identity`]）认的是**像素指纹**，不是名字；
//! 这里读的是**名字**，只用来显示与提示词上下文。
//! ⇒ 名字读错/读不到**不会**锁错人、也**不会**不推理。

use chatservant_capture::ocr;
use chatservant_core::frame::Rect;

/// OCR 读会话名用的带高，**与指纹那块刻意不同**。
///
/// ## ⚠ 2026-10-21 订正：决定读不读得到的**不是带高，是放大倍数**
///
/// 这块注释先后写错过两次，两次都是**量错了变量**：
///
/// 1. 2026-10-07 那张表「40px 0 行 / 60px 1 行 / 100px 1 行」——
///    今天复现不出来（原始带子已不可考），而且当时**只量了一个倍率**。
/// 2. 2026-10-21 我自己写过一版「PP-OCR 40~200px 全稳、WinRT 要 200px 才稳」
///    ——**那张表也量错了**：它是在**放大 2×** 下去扫带高，
///    于是把「2× 读不到」读成了「这个带高读不到」。
///
/// 今天按**生产几何**复刻的那条带子（真机帧 `chat.y0 = 31`、推导出的头部行
/// y49..61 ⇒ 带子 (308,31)-(708,91) = 400×60），**只改放大倍数**：
///
/// ```text
/// 倍率   PP-OCR（生产默认）      WinRT（回退）
///  1×    1 行 / 2 字 ✓          0 行 ✗
///  2×    1 行 / 2 字 ✓          0 行 ✗   ← 原先这条路的倍数
///  3×    1 行 / 2 字 ✓          1 行 / 2 字 ✓
///  4×    1 行 / 2 字 ✓          1 行 / 2 字 ✓
/// ```
///
/// ⇒ **PP-OCR 在 1×~4× 全稳**（它本来就吃得下 14px 小字，不挑倍率）；
///   **WinRT 对这条中文名要 ≥3×**（2× 读不到，3×/4× 都读得到）。
/// ⇒ **带高不是变量**：36px 与 60px 两种带子在同一倍率下结果完全一样。
/// ⇒ **颜色也不是变量**：原色与反色结果一样
///   （探针那段「原色 / 反色」对照的**反色**那一遍其实是 4×，
///   见 [`PEER_NAME_UPSCALE`]——不查清楚就会把「反色有用」写进生产代码）。
///
/// ## ⚠⚠ 2026-10-21 晚：上面那句「WinRT 要 ≥3×」**带前提**，别当成通则
///
/// 晚些时候在**真机实时帧**上做了反向对照（把倍数退回 2）：
///
/// | 带子里的名字 | PP-OCR 2× | WinRT 2× | WinRT 3× |
/// |---|---|---|---|
/// | **中文**（存档帧） | 读到 ✓ | **读不到 ✗** | 读到 ✓ |
/// | **ASCII**（实时帧） | 读到 ✓ | **读到 ✓** | 读到 ✓ |
///
/// ⇒ **同一个倍率，文本内容不同，结果就不同**：
///   「WinRT 要 3×」的准确说法是「**中文名**在 WinRT 上要 3×」。
///   ASCII 名在 2× 就够。
///
/// ⚠ 这个对照**没有把「文本种类」单独隔离干净**：
/// 两条带子虽然同宽高（都是 400×60）、同机器、同 DPI（两个帧高都是 900），
/// 但**取自不同时刻、不同会话**，像素渲染不完全同源。
/// ⇒ 按纪律，**不把它写成规律**，只写成「在中文名上实测如此」。
///
/// ⇒ 这也解释了为什么 `PEER_NAME_UPSCALE = 3` 是安全的：
///   它对 PP-OCR **零增益**（PP-OCR 在 1× 就读得出），
///   对 ASCII 名**零增益**（2× 就够），
///   只在「**WinRT + 中文名**」这一格里**从读不到变成读得到**。
///   代价只是多放大一档（读数零影响）。
///
/// ## 所以：带高 72 不构成约束，**倍数**才是
///
/// 生产默认引擎是 PP-OCR，它在 1× 就读得出 ⇒ 带高 72 对它不构成约束 ⇒ 不动。
/// WinRT 回退路径在 **2×** 下读不到**中文**名 ⇒ 面板标题空、提示词里没有对方名；
/// 但**闸照常工作**（闸比的是像素指纹，不是名字，见 [`crate::identity`]），
/// 所以影响面是「看不到名字」，**不是**「锁错人 / 不推理」。
///
/// 2026-10-14 票 31：这行原先写的是「指纹那块继续用 `HEAD_BAND_H`」，
///   而那个常量**连同 `header_band_rect` 一起删掉了**——闸那块不再有固定高度，
///   高度由 `HeaderPrint::discover` 从像素推出（真机实测 11 ⇒ 量化到 12）。
///   这个 72 只管**这里**（取名字时的 OCR 窗口），与闸的取样范围无关。
pub const PEER_NAME_BAND_H: i32 = 72;

/// 读会话名那条路的**放大倍数**——**它自己的**，不是消息那条路的。
///
/// ## 为什么不能跟消息共用一个
///
/// 消息那条路的 2×（[`crate::OCR_UPSCALE`]）是给**整帧**定的，
/// 而这里是**一条窄带子**里的一个 11px 小字——两者的需求**相反方向**：
/// 窄带里的**中文名**在 2× 下 WinRT 读不到
/// （见 [`PEER_NAME_BAND_H`] 那张表与它下面的反向对照表），要 3×。
///
/// ⚠ 顺带纠正探针一个**标签骗人**的地方：`xtask perceive` 那段
/// 「原色 / 反色」对照里，**反色**那一遍其实是把 2× 的视图**再放大一次**（4×）
/// ⇒ 它能读到的原因是**倍率**，不是**反色**。
///
/// 3× 是**两边都过的最小值**：PP-OCR 1×~4× 都读得到，
/// WinRT 对**中文名**要 ≥3×（对 ASCII 名 2× 就够——见 [`PEER_NAME_BAND_H`]
/// 里那张反向对照表；⚠ 那张表**没有把「文本种类」单独隔离干净**，
/// 所以这里只写「中文名上实测如此」，不写成通则）。
pub const PEER_NAME_UPSCALE: u32 = 3;

/// 标题墨迹右边界**之外**再留这么多像素（帧坐标）。
///
/// ## 为什么要有这个余量
///
/// 墨迹的**右边界**是最后一个墨像素所在的那一列，而字的**笔画**
/// 可能正好收在这一列上 —— 裁到那一列等于贴着笔画切一刀。
/// 留 8 px 余量（≈ 一个汉字的 1/3）让最后一个字完整。
///
/// ⚠ 真机实测：「小号」的墨迹到偏移 47，加余量后裁到 55，
/// 而对照实验里用的是 112 px 宽（比这宽得多）⇒ 结论一致：
/// 裁到「墨迹右边界 + 余量」与裁到 112 px 的**读数逐字相同**。
pub const PEER_NAME_BAND_PAD: i32 = 8;

/// 从**推导出的头部行**里读会话名。坐标系要求同 [`crate::identity`]——**整帧**。
///
/// ## 这里原来读的是消息区顶部、再改到 `chat.y0` 之上，两次都读不出名字
///
/// 票 30 真机 `peer=""` 查了三轮取证才落到「那块像素里没有名字」这个事实上；
/// 修的时候又按「标题栏在 `chat.y0` 之上」猜了一次，**仍然读不出**——
/// 真机上会话名在 `chat.y0` **之下**（y 49..59，`chat.y0 = 31`）。
///
/// ⇒ 现在**不猜**：矩形由
/// [`crate::identity::HeaderPrint::discover`] 从像素里推出来，
/// 这里直接用它。判据
/// `identity::tests::discover_follows_the_header_line_wherever_it_moves`
/// 守着「挪了位置也跟得上」；把它退回写死 y 时那条立刻红。
///
/// 带子的**位置**不写死：高度由推导出的行加上余量凑成（余量是给
/// 「窄带不收」那种引擎留的，见 [`PEER_NAME_BAND_H`] 的实测），
/// 且不越过 `chat` 的下沿。
///
/// 返回 `None` = **没读出名字**（不是「没有名字」，也不是「认错人」）。
pub fn read_peer_name(
    frame: &chatservant_capture::Frame,
    print: &crate::identity::HeaderPrint,
    head: Rect,
    chat: Rect,
) -> Option<String> {
    // 上下各留一点余量：11px 的行直接丢给 OCR，它会返回 0 行。
    let pad = (PEER_NAME_BAND_H - head.height()).max(0) / 2;
    let y0 = (head.y0 - pad).max(chat.y0);
    let y1 = (head.y1 + pad).min(chat.y1);
    if y1 <= y0 {
        return None;
    }
    // ⚠⚠ **裁到标题墨迹的右边界**（2026-10-23 真机实测）。
    //
    // ## 为什么必须裁
    //
    // 头带宽 400 px，而会话名只占左端几十 px（真机「小号」= 偏移 20..47），
    // 其余 350+ px 是**空面板**。可 det 的输入尺寸按
    // 「**最短边**不足 736 就等比放大」算（`ocr_pp_pipeline::det_size`），
    // 于是 400×60 的带子在 3× 放大后是 1200×180 ⇒
    // 短边补到 736 ⇒ **长宽比 6.67 把宽度撑到 4928**
    // ⇒ det 输入 **4928×736 = 3.63 Mpx**，
    // 是消息区那路（1088×736 = 0.80 Mpx）的 **4.53 倍**。
    //
    // ## 裁了以后
    //
    // | 窄带 | det 输入 | det 推理（debug） | 读数 |
    // |---|---|---|---|
    // | 400×60（现状） | 4928×736 | ~2900 ms | 小号 |
    // | 112×60（裁窄） | **1376×736** | **884 ms** | **小号** |
    //
    // ⇒ **3.3 倍提速，读数逐字相同**（框位置 x=31、宽 117，两边一致）。
    // 而它省下的正是「切换会话那一轮」的最大一块开销。
    //
    // ## 为什么宽度不能写死
    //
    // 「文件传输助手」6 个字比「小号」宽得多，写死 112 px 会把长名字切掉
    // ⇒ 面板显示的名字被截断（且**没有任何报错**）。
    // ⇒ 宽度由**推导出的标题墨迹右边界**决定
    // （[`HeaderPrint::title_right`]，帧坐标），不是常数。
    //
    // ⚠ 右边界取自**标题那一行**（`discover` 推出来的 12px 行），
    // 不是整条 72px 头带 —— 头带下半截会混进消息区顶部那张图片的边缘
    // （真机实测偏移 75..87、194..212 两段），拿它当右边界会把
    // 图片边缘一起裁进来。
    let right = print.title_right().max(head.x0) + PEER_NAME_BAND_PAD;
    let strip = frame.crop(Rect::new(head.x0, y0, right.min(head.x1), y1))?;
    // 小字要放大才认得准——与 `read_lines` 同一个理由（ADR-0002 补记）。
    //
    // ⚠ **倍数是这条路自己的（3×），重采样方式跟引擎走**（2026-10-21，票 77）：
    // 「放大几倍」在这条路上**不能**沿用消息那条路的 2×
    // （窄带在 2× 下 WinRT 读不到，见 [`PEER_NAME_UPSCALE`]），
    // 而「用哪种重采样」是**引擎的属性**——手写一份就会在换引擎时漂
    // （票 72 已经为消息那条路付过一次这个代价）。
    // 实测**换重采样对读数零影响**（PP-OCR 两种逐字相同，编辑距离 0；
    // WinRT 在 3× 下两种也相同）⇒ 跟引擎走不是为了今天的读数，
    // 是为了**换引擎时它不会悄悄漂**。
    let resample = ocr::engine().resample();
    let view = strip.upscaled(PEER_NAME_UPSCALE, resample)?;
    let ocr = ocr::recognize(&view).ok()?;
    ocr.lines
        .iter()
        .map(|l| l.text.trim())
        .find(|t| !t.is_empty())
        .map(str::to_string)
}

#[cfg(test)]
mod tests {
    /// 把源码里的**注释行**去掉，只留代码。
    ///
    /// ⚠ 为什么必须去掉：文档注释里**要提到**那些被禁的名字
    /// （例如「这里不能沿用 `OCR_UPSCALE`」）——按整段源码扫会误判。
    fn code_only(src: &str) -> String {
        src.lines()
            .filter(|l| {
                let t = l.trim_start();
                !t.starts_with("///")
                    && !t.starts_with("//")
                    && !t.starts_with("/*")
                    && !t.starts_with('*')
            })
            .collect::<Vec<_>>()
            .join("\n")
    }

    /// **读会话名这条路也不许自己拼 OCR 配方。**
    ///
    /// 配方由**引擎**决定（`ocr::Engine::resample`）：手写一份就会在
    /// 换引擎时悄悄漂（票 72 为消息那条路付过一次这个代价）。
    ///
    /// ⚠ 这条守卫量的对象是**事实来源**：它断言的是「这条路上没有
    /// 硬编码的重采样」，而不是「某个常量的值」——
    /// 引擎换了要跟着换，守卫才绿。
    #[test]
    fn the_name_path_does_not_hand_roll_the_ocr_recipe() {
        let source = include_str!("peer.rs");
        let prod = source.split("#[cfg(test)]").next().unwrap_or(source);
        let code = code_only(prod);
        assert!(
            !code.contains("upscaled_nearest") && !code.contains("upscaled_bilinear"),
            "读会话名那条路又自己挑重采样方式了——配方必须由引擎决定"
        );
        assert!(
            !code.contains("Resample::"),
            "读会话名那条路又写死了重采样方式——配方必须由引擎决定"
        );
        assert!(
            code.contains("ocr::engine()"),
            "读会话名那条路没向引擎要配方——重采样方式该由引擎决定"
        );
        // ⚠ **不许沿用消息那条路的倍数**（2×，2026-10-21，票 77）：
        // 消息那个 2× 是给**整帧**定的，而这里是**窄带里 11px 的一个词**——
        // 真机实测 WinRT 在 2× 下读不到、3× 才读得到（`PEER_NAME_UPSCALE`）。
        assert!(
            !code.contains("OCR_UPSCALE"),
            "读会话名那条路又用上消息那条路的 2× 了——窄带在 2× 下 WinRT 读不到名字"
        );
        assert!(
            code.contains("PEER_NAME_UPSCALE"),
            "读会话名那条路没用自己的倍数常量——它的需求与整帧相反"
        );
    }

    /// 读会话名那条路的**放大倍数必须是 3**。
    ///
    /// 判据来自 2026-10-21 的真机实测（`target/probe/name/`，不入库）：
    /// 按**生产几何**复刻的那条带子（`chat.y0 = 31`、头部行 y49..61
    /// ⇒ 400×60），WinRT 在 **2× 读不到、3× 读到**；
    /// PP-OCR 在 1×~4× **都**读到 ⇒ **3 是两边都过的最小值**。
    ///
    /// ⚠ 这条是**源码级**断言，**不是** `assert!(PEER_NAME_UPSCALE >= 3)`：
    /// 后者的条件是编译期常量 ⇒ clippy 的 `assertions_on_constants` 判它
    /// 「这个断言的值是常量」而**报错**（`-D warnings` ⇒ 门禁红）。
    /// ⇒ 改成扫源码里那行字面量：倍数被改成 2 就立刻红。
    ///
    /// ⚠ 它钉的是**常数**，不是**行为**——行为那半（真机帧上读得到名字）
    /// **在 CI 上验不了**（帧是本机专属、gitignored），由票 77 记着。
    #[test]
    fn the_name_band_scale_is_three() {
        let source = include_str!("peer.rs");
        let prod = source.split("#[cfg(test)]").next().unwrap_or(source);
        assert!(
            prod.contains("const PEER_NAME_UPSCALE: u32 = 3;"),
            "读会话名的倍数被改了——WinRT 在 2× 下读不到窄带里的名字（2026-10-21 实测）"
        );
    }
}
